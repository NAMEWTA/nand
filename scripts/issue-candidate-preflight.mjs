import fs from 'node:fs';
import assert from 'node:assert/strict';
const file = 'scripts/issue-candidate-patch.mjs';
let source = fs.readFileSync(file, 'utf8');
const slash = String.fromCharCode(92);
source = source.replace('/' + slash + slash + '.tsx?$/', '/' + slash + '.tsx?$/');
source = source.replaceAll(slash.repeat(2) + '"', '"');
fs.writeFileSync(file, source);
let css = fs.readFileSync('styles.css', 'utf8');
const anchor = '.dashboard-quicknote-empty {';
assert.ok(css.includes(anchor));
assert.ok(!css.includes('.dashboard-quicknote-empty-text {'));
css = css.replace(anchor, '.dashboard-quicknote-empty-text {\n}\n\n' + anchor);
fs.writeFileSync('styles.css', css);
const testFile = 'scripts/verify-automation.ts';
let test = fs.readFileSync(testFile, 'utf8');
const raw = String.raw`let raw = '# Board\n\n## Column\n\n### Tasks\n\n- [ ] Parent\n  - [ ] Nested ⏰ 2026-09-27 09:00\n';`;
assert.ok(test.includes(raw), 'The original ownership/idempotence fixture must be present');
test = test.replace(raw, raw.replace('## Column', '## Todo'));
fs.writeFileSync(testFile, test);
